/**
 * Self-contained "Connect GROM Server" settings content (Phase 6.3).
 *
 * It owns the single process-wide connection manager via the registry, so there
 * is one connection for the whole app and the settings UI is only a view over it.
 * OFF by default; turning it off drops only this app's client state and never
 * touches the Grom server application itself.
 */
@Composable
fun GromConnectSettings() {
    val context = LocalContext.current
    val manager = remember { GromConnectionRegistry.get(context) }
    val snapshot by manager.snapshot.collectAsState()
    val scope = rememberCoroutineScope()
    val clipboard = LocalClipboardManager.current

    var address by remember { mutableStateOf(manager.config().baseUrl) }
    var authMethod by remember { mutableStateOf(manager.config().authMethod) }
    var password by remember { mutableStateOf("") }
    var passwordSaved by remember { mutableStateOf(manager.hasPassword()) }
    var keyGenerated by remember { mutableStateOf(manager.hasKey()) }
    var keyId by remember { mutableStateOf(manager.config().keyId) }
    var publicKey by remember { mutableStateOf(manager.config().publicKey) }
    var keyError by remember { mutableStateOf<String?>(null) }
    var llmAvailable by remember { mutableStateOf<Boolean?>(null) }

    val proxy = remember { GromLlmProxyAdapter(manager) }
    LaunchedEffect(snapshot.phase, snapshot.services) {
        llmAvailable = if (snapshot.phase == GromPhase.CONNECTED) {
            runCatching { proxy.isAvailable() }.getOrDefault(false)
        } else {
            null
        }
    }

    Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
        // Master switch: controls this app's connection, never the Grom server.
        Row(verticalAlignment = Alignment.CenterVertically, modifier = Modifier.fillMaxWidth()) {
            Column(Modifier.weight(1f)) {
                Text(stringResource(R.string.grom_enable), fontWeight = FontWeight.SemiBold, fontSize = 14.sp)
                Text(stringResource(R.string.grom_enable_subtitle), fontSize = 11.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
            }
            Switch(
                checked = snapshot.enabled,
                onCheckedChange = { enabled ->
                    manager.setEnabled(enabled)
                    if (enabled) scope.launch { manager.connect() }
                },
            )
        }

        OutlinedTextField(
            value = address,
            onValueChange = { address = it },
            label = { Text(stringResource(R.string.grom_address)) },
            singleLine = true,
            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Uri),
            enabled = !snapshot.enabled,
            modifier = Modifier.fillMaxWidth(),
        )
        OutlinedButton(onClick = { manager.setBaseUrl(address) }, modifier = Modifier.fillMaxWidth()) {
            Text(stringResource(R.string.grom_save_address))
        }

        // Authentication method + credential.
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.fillMaxWidth()) {
            OutlinedButton(
                onClick = {
                    authMethod = GromConfig.AUTH_PASSWORD
                    manager.setAuthMethod(GromConfig.AUTH_PASSWORD)
                },
                modifier = Modifier.weight(1f),
                border = if (authMethod == GromConfig.AUTH_PASSWORD) BorderStroke(1.dp, MaterialTheme.colorScheme.primary) else null,
            ) { Text(stringResource(R.string.grom_auth_password), maxLines = 1) }
            OutlinedButton(
                onClick = {
                    authMethod = GromConfig.AUTH_KEY
                    manager.setAuthMethod(GromConfig.AUTH_KEY)
                },
                modifier = Modifier.weight(1f),
                border = if (authMethod == GromConfig.AUTH_KEY) BorderStroke(1.dp, MaterialTheme.colorScheme.primary) else null,
            ) { Text(stringResource(R.string.grom_auth_key), maxLines = 1) }
        }

        when (authMethod) {
            GromConfig.AUTH_PASSWORD -> {
                OutlinedTextField(
                    value = password,
                    onValueChange = { password = it },
                    label = { Text(stringResource(R.string.grom_password_label)) },
                    singleLine = true,
                    visualTransformation = PasswordVisualTransformation(),
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                    modifier = Modifier.fillMaxWidth(),
                )
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp), verticalAlignment = Alignment.CenterVertically) {
                    Button(onClick = {
                        manager.savePassword(password)
                        passwordSaved = manager.hasPassword()
                    }) { Text(stringResource(R.string.grom_password_save)) }
                    if (passwordSaved) {
                        Text(stringResource(R.string.grom_password_saved), fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
            }
            GromConfig.AUTH_KEY -> {
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp), verticalAlignment = Alignment.CenterVertically) {
                    Button(onClick = {
                        keyError = null
                        val identity = manager.generateKey()
                        if (identity == null) {
                            keyError = context.getString(R.string.grom_key_unavailable)
                        } else {
                            keyGenerated = true
                            keyId = identity.keyId
                            publicKey = identity.publicKey
                        }
                    }) { Text(stringResource(R.string.grom_generate_key)) }
                    if (keyGenerated) {
                        Text(stringResource(R.string.grom_key_generated), fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
                keyError?.let { Text(it, fontSize = 12.sp, color = MaterialTheme.colorScheme.error) }
                if (publicKey.isNotBlank()) {
                    Surface(
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(10.dp),
                        color = MaterialTheme.colorScheme.surfaceVariant,
                    ) {
                        Column(Modifier.padding(10.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                            Text(stringResource(R.string.grom_public_key), fontSize = 11.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                            Text(publicKey, fontSize = 11.sp, fontFamily = FontFamily.Monospace, maxLines = 3, overflow = TextOverflow.Ellipsis)
                            Row(verticalAlignment = Alignment.CenterVertically) {
                                Text("keyId $keyId", fontSize = 11.sp, fontFamily = FontFamily.Monospace, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Spacer(Modifier.weight(1f))
                                TextButton(onClick = { clipboard.setText(AnnotatedString(publicKey)) }) {
                                    Text(stringResource(R.string.grom_copy))
                                }
                            }
                        }
                    }
                }
            }
        }

        // Actions.
        if (snapshot.enabled) {
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.fillMaxWidth()) {
                Button(onClick = { scope.launch { manager.connect() } }, modifier = Modifier.weight(1f)) {
                    Text(stringResource(R.string.grom_connect))
                }
                OutlinedButton(onClick = { scope.launch { manager.reconnect() } }, modifier = Modifier.weight(1f)) {
                    Text(stringResource(R.string.grom_reconnect))
                }
                OutlinedButton(onClick = { manager.disconnect() }, modifier = Modifier.weight(1f)) {
                    Text(stringResource(R.string.grom_disconnect))
                }
            }
        }

        GromStatusCard(snapshot)

        snapshot.message?.let {
            Text(it, fontSize = 12.sp, color = phaseColor(snapshot.phase))
        }

        if (snapshot.phase == GromPhase.CONNECTED) {
            llmAvailable?.let { available ->
                Text(
                    stringResource(
                        if (available) R.string.grom_llm_proxy_available else R.string.grom_llm_proxy_unavailable,
                    ),
                    fontSize = 12.sp,
                    color = if (available) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
    }
}

@Composable
private fun GromStatusCard(snapshot: GromConnectionSnapshot) {
    Surface(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(14.dp),
        color = MaterialTheme.colorScheme.surface,
        border = BorderStroke(1.dp, MaterialTheme.colorScheme.outlineVariant),
    ) {
        Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(stringResource(R.string.grom_status), fontWeight = FontWeight.SemiBold, fontSize = 14.sp)
                Spacer(Modifier.weight(1f))
                Text(snapshot.phase.name, fontSize = 13.sp, fontWeight = FontWeight.SemiBold, color = phaseColor(snapshot.phase))
            }
            HorizontalDivider(color = MaterialTheme.colorScheme.outlineVariant.copy(alpha = 0.4f))
            snapshot.serverVersion?.let { StatusRow(stringResource(R.string.grom_server), it) }
            snapshot.apiVersion?.let { StatusRow(stringResource(R.string.grom_api), it.toString()) }
            snapshot.schema?.let { StatusRow("schema", it) }
            snapshot.principal?.let { StatusRow(stringResource(R.string.grom_principal), it) }
            if (snapshot.capabilities.isNotEmpty()) {
                StatusRow(stringResource(R.string.grom_scopes), snapshot.capabilities.joinToString(", "))
            }
            if (snapshot.phase == GromPhase.CONNECTED) {
                Text(stringResource(R.string.grom_services), fontSize = 12.sp, fontWeight = FontWeight.SemiBold)
                if (snapshot.services.isEmpty()) {
                    Text(stringResource(R.string.grom_no_services), fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                } else {
                    snapshot.services.forEach { service ->
                        Text("${service.title} · ${service.description.ifBlank { service.id }}", fontSize = 12.sp)
                        Text(
                            stringResource(R.string.grom_callable_ops) + ": " +
                                service.scopedOps.joinToString(", ").ifBlank { stringResource(R.string.grom_none) },
                            fontSize = 11.sp,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
            }
        }
    }
}

@Composable
private fun StatusRow(label: String, value: String) {
    Row {
        Text("$label: ", fontSize = 12.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
        Text(value, fontSize = 12.sp, fontWeight = FontWeight.Medium)
    }
}

@Composable
private fun phaseColor(phase: GromPhase): Color = when (phase) {
    GromPhase.CONNECTED -> Color(0xFF16A34A)
    GromPhase.CONNECTING -> MaterialTheme.colorScheme.primary
    GromPhase.AUTH_REQUIRED -> Color(0xFFD97706)
    GromPhase.INCOMPATIBLE, GromPhase.ERROR -> MaterialTheme.colorScheme.error
    GromPhase.DISCONNECTED, GromPhase.OFF -> MaterialTheme.colorScheme.onSurfaceVariant
}
